"""Writes src/introVoiceTiming.js: when each intro voice line is speaking.

For every recording in src/assets/audio/voice/introduction/ it finds the
spans of speech (between pauses of 0.25 s or more, quieter than -40 dB) with
ffmpeg's silencedetect. TeacherIntro types a line's text across those spans,
so the text waits while the voice pauses between sentences.

Re-run after replacing or adding intro recordings (needs ffmpeg/ffprobe on
PATH; standard library only):

    python scripts/voice_timing.py
"""

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VOICE_DIR = ROOT / 'src' / 'assets' / 'audio' / 'voice' / 'introduction'
OUT = ROOT / 'src' / 'introVoiceTiming.js'
NOISE_DB = -40
MIN_PAUSE_S = 0.25
# (language key, file tag) and (speaker key, file prefix, line count)
LANGS = [('en', 'eng'), ('ur', 'urdu')]
SPEAKERS = [('teacher', 'teacher', 8), ('robo', 'robot', 6)]


def duration(path):
    out = subprocess.run(
        ['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(path)],
        capture_output=True, text=True, check=True,
    ).stdout
    return float(out)


def speech_spans(path):
    log = subprocess.run(
        ['ffmpeg', '-hide_banner', '-i', str(path), '-af',
         f'silencedetect=n={NOISE_DB}dB:d={MIN_PAUSE_S}', '-f', 'null', '-'],
        capture_output=True, text=True, check=True,
    ).stderr
    total = duration(path)
    starts = [float(x) for x in re.findall(r'silence_start: ([\d.]+)', log)]
    ends = [float(x) for x in re.findall(r'silence_end: ([\d.]+)', log)]
    silences = list(zip(starts, ends + [total] * (len(starts) - len(ends))))
    spans, cursor = [], 0.0
    for s, e in silences:
        if s > cursor:
            spans.append((cursor, s))
        cursor = max(cursor, e)
    if cursor < total:
        spans.append((cursor, total))
    return [(round(s, 2), round(e, 2)) for s, e in spans if e - s > 0.02]


def main():
    lines = [
        '// Generated by scripts/voice_timing.py - do not edit by hand.',
        '// Speech spans [start, end] (seconds into the recording) of each Level 1',
        '// intro voice line, in the same order as App.jsx INTRO_VOICES.',
        'export const INTRO_VOICE_SPANS = {',
    ]
    for lang, tag in LANGS:
        lines.append(f'  {lang}: {{')
        for speaker, prefix, count in SPEAKERS:
            lines.append(f'    {speaker}: [')
            for n in range(1, count + 1):
                name = f'introduction_{prefix}_{tag}_line{n}.mp3'
                spans = speech_spans(VOICE_DIR / name)
                body = ', '.join(f'[{s}, {e}]' for s, e in spans)
                lines.append(f'      [{body}], // {name}')
            lines.append('    ],')
        lines.append('  },')
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
